// A crash bad enough for the rescue, start to finish, a shot at each stage:
// node tools/rescue.mjs <outdir> [park] [gore=on]
import { chromium } from 'playwright-core';
import { CHROME, ANGLE } from './chrome.mjs';
import fs from 'node:fs';
const [out = 'shots/rescue', park = 'yard', gore = 'on'] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: CHROME, headless: true, args: [ANGLE, '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message, e.stack?.split('\n')[1]));
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 300)); });
await page.addInitScript((g) => { try { localStorage.setItem('alpenglow.gore', g); } catch { /* */ } }, gore);
await page.goto(`http://127.0.0.1:${process.env.PORT ?? 5260}/?park=${park}&menu=0&mode=run&tod=bluebird&fixdpr=1`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__ready === true, null, { timeout: 180000 });
await page.waitForTimeout(3000);
await page.evaluate(() => { const g = window.__game, C = window.__course, p = g.player; const z = 1300; p.place(C.centerX(z), z, null, 20); p.startCrash('tree', 20); });
const st = () => page.evaluate(() => { const r = window.__game.rescue; return { phase: r.phase, active: r.active, t: +r.t.toFixed(1), state: window.__game.state }; });
const shot = async (name, wait) => { await page.waitForTimeout(wait); console.log(name, JSON.stringify(await st())); await page.screenshot({ path: `${out}/${name}.jpg`, quality: 75 }); };
await shot('1_down', 1800);
await shot('2_inbound', 6000);
await shot('3_lower', 6000);
await shot('4_winch', 4500);
await shot('5_away', 3500);
await shot('6_hospital', 4500);
await shot('7_pick', 2500);
await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
await shot('8_lift', 4000);
await shot('9_lift2', 14000);
await shot('10_drop', 14500);
console.log('player', JSON.stringify(await page.evaluate(() => { const p = window.__game.player; return { z: p.pos.z | 0, crash: p.crash, held: !!p.held, vis: p.model.group.visible }; })));
await browser.close();
