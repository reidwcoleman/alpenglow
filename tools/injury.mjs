// A severe crash up close: shots as it tumbles and once it's stopped. node tools/injury.mjs <out-prefix> [speed]
import { chromium } from 'playwright-core';
import { CHROME, ANGLE } from './chrome.mjs';
const [out, speed = '24'] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: CHROME, headless: true, args: [ANGLE, '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message, e.stack?.split('\n')[1]));
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 300)); });
await page.goto(`http://127.0.0.1:5260/?park=yard&menu=0&mode=run&tod=bluebird&fixdpr=1`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__ready === true, null, { timeout: 180000 });
await page.waitForTimeout(3000);
await page.evaluate((sp) => { const g = window.__game, C = window.__course, p = g.player; const z = 1300; p.place(C.centerX(z), z, null, sp); p.crashSpeed = sp; p.startCrash('tree', sp); }, Number(speed));
const cam = (a, d, h) => page.evaluate(([a, d, h]) => { const p = window.__game.player.pos; window.__freeCam = { pos: [p.x + Math.sin(a) * d, p.y + h, p.z + Math.cos(a) * d], look: [p.x, p.y + 0.3, p.z], fov: 50 }; }, [a, d, h]);
await cam(0.6, 6, 2.5); await page.waitForTimeout(250); await page.screenshot({ path: `${out}_0.jpg`, quality: 80 });
await page.waitForTimeout(350); await page.screenshot({ path: `${out}_1.jpg`, quality: 80 });
await page.waitForTimeout(4200);
await cam(0.3, 3.4, 2.2); await page.waitForTimeout(300); await page.screenshot({ path: `${out}_2.jpg`, quality: 80 });
await cam(2.4, 3.0, 1.6); await page.waitForTimeout(300); await page.screenshot({ path: `${out}_3.jpg`, quality: 80 });
console.log(await page.evaluate(() => { const I = window.__game.injuries; return JSON.stringify({ bits: I.bits.length, splats: I.splats.length, stumps: I.stumps.length }); }));
await browser.close();
